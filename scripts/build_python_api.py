"""Generate checked-in, statically typed Python facades from calculation metadata.

Run after adding a calculation or changing an output specification. Generated files
are ordinary Python sources; consumers do not run this script or use code generation.
"""
from collections import defaultdict
from pathlib import Path
import keyword
import sys
import types
from typing import Annotated, Any, Literal, Union, get_args, get_origin

ROOT_DIR = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT_DIR / "src"))

from api581.core import REGISTRY, NonNegative, Fraction, Model
from api581.contracts import SPECS

ROOT = ROOT_DIR / "src/api581"


def pascal(value):
    return "".join(part.capitalize() for part in value.replace("/", "-").split("-"))


def annotation(value):
    if value is Any:
        return "Any"
    if value is type(None):
        return "None"
    origin, args = get_origin(value), get_args(value)
    if origin is Annotated:
        if value == Fraction:
            return "Fraction"
        if value == NonNegative:
            return "NonNegative"
        raise ValueError(f"Unmapped constrained type: {value}")
    if origin is Literal:
        return "Literal[" + ", ".join(repr(x) for x in args) + "]"
    if origin in (Union, types.UnionType):
        return " | ".join(annotation(x) for x in args)
    if origin:
        return origin.__name__ + "[" + ", ".join(annotation(x) for x in args) + "]"
    return value.__name__


def nested_models(model, seen=None):
    """Expose nested request types so typed consumers never need kernel imports."""
    seen = set() if seen is None else seen
    for field in model.model_fields.values():
        pending = [field.annotation]
        while pending:
            value = pending.pop()
            if isinstance(value, type) and issubclass(value, Model) and value not in seen:
                seen.add(value)
                nested_models(value, seen)
            else:
                pending.extend(get_args(value))
    return seen


def main():
    lines = ['"""Generated typed output models. Rebuild with scripts/build_python_api.py."""',
             "from typing import Any, Literal", "from .core import Model, NonNegative, Fraction", ""]
    for identifier, fields in SPECS.items():
        lines += [f"class {pascal(identifier)}Output(Model):"]
        lines += [f"    {name}: {annotation(t)}" for name, t in fields.items()]
        lines += ["", ""]
    lines += ["class PlanningTargetCrossingOutput(Model):",
              '    status: Literal["already_exceeded", "crossing", "not_crossed_within_horizon"]',
              "    crossing_years: NonNegative | None", "    horizon_years: NonNegative | None = None", "", "",
              "class RiskAssessmentOutput(Model):",
              '    integration_scope: Literal["supplied_damage_and_consequences"]',
              "    management_factor: NonNegative", "    generic_frequencies: FrequencyGenericOutput",
              "    scenarios: list[dict[str, Any]]", "    risk: RiskAggregateOutput", "", "",
              "class RiskAssessmentFromDamageOutput(Model):",
              '    integration_scope: Literal["combined_damage_and_supplied_consequences"]',
              "    management_factor: NonNegative", "    generic_frequencies: FrequencyGenericOutput",
              "    scenarios: list[dict[str, Any]]", "    risk: RiskAggregateOutput",
              "    damage_factor: DamageCombineOutput", "", "",
              "OUTPUT_MODELS = {"]
    lines += [f"    {identifier!r}: {pascal(identifier)}Output," for identifier in REGISTRY]
    lines += ["    'risk/assessment-from-damage': RiskAssessmentFromDamageOutput,"]
    lines += ["}", ""]
    (ROOT / "outputs.py").write_text("\n".join(lines), encoding="utf-8")

    groups = defaultdict(list)
    for identifier, calc in REGISTRY.items():
        domain, name = identifier.split("/")
        name = name.replace("-", "_")
        if keyword.iskeyword(name):
            name += "_"
        groups[domain].append((identifier, name, calc))
    folder = ROOT / "api"
    folder.mkdir(exist_ok=True)
    for domain, entries in groups.items():
        lines = [f'"""Public {domain} calculations. Inputs and outputs use named SI units.',
                 'Generated by scripts/build_python_api.py; inspect the request model for fields.',
                 '"""', "from ..core import Context", "from ..result import CalculationResult, calculate", ""]
        exports = []
        top_aliases = {pascal(identifier.split("/")[1])+"Input" for identifier, _, _ in entries}
        nested = set().union(*(nested_models(calc.model) for _, _, calc in entries))
        nested_names = defaultdict(list)
        for model in nested:
            nested_names[model.__name__+"Input"].append(model)
        for alias, models in sorted(nested_names.items()):
            for model in sorted(models, key=lambda m:(m.__module__,m.__name__)):
                name = alias if len(models) == 1 and alias not in top_aliases else pascal(model.__module__.split(".")[-1])+alias
                if name in exports or name in top_aliases:
                    raise ValueError(f"Nested model public-name collision: {domain}.{name}")
                module = model.__module__.removeprefix("api581.")
                lines += [f"from ..{module} import {model.__name__} as {name}"]
                exports.append(name)
        lines += [""]
        for identifier, name, calc in entries:
            cls = pascal(identifier.split("/")[1])
            module = calc.model.__module__.removeprefix("api581.")
            output = pascal(identifier) + "Output"
            lines += [f"from ..{module} import {calc.model.__name__} as {cls}Input",
                      f"from ..outputs import {output} as {cls}Output", "",
                      f"def {name}(inputs: {cls}Input, *, context: Context | None = None) -> CalculationResult[{cls}Output]:",
                      f"    {calc.title!r}",
                      f"    return calculate({identifier!r}, inputs, output_type={cls}Output, context=context)", "", ""]
            exports += [name, cls + "Input", cls + "Output"]
        lines += [f"__all__ = {exports!r}", ""]
        (folder / f"{domain}.py").write_text("\n".join(lines), encoding="utf-8")
    (folder / "__init__.py").write_text(
        '"""Typed public Python APIs grouped by engineering domain."""\n'
        + "from . import " + ", ".join(sorted(groups)) + "\n\n"
        + f"__all__ = {sorted(groups)!r}\n", encoding="utf-8")
    (ROOT / "py.typed").touch()
    print(f"Generated {len(REGISTRY)} typed Python functions in {len(groups)} domains")


if __name__ == "__main__":
    main()
