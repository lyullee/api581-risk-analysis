"""Extract visually checked 2016 amine table rows; no runtime kernel imports."""
import hashlib
import json
import re
from pprint import pformat
from pathlib import Path

text=Path('tmp/pdfs/API-581-2016.txt').read_text(encoding='utf-8')
tables={}
cells=[]
for page in (384,385,386,387):
    body=text.split(f'=== PDF PAGE {page} ===')[1].split('=== PDF PAGE')[0]
    rows=[]
    for line in body.splitlines():
        line=re.sub(r'(\d)\s+\.(\d)',r'\1.\2',line)
        # Remove optional printed loading and HSAS row key, then twelve rate cells.
        tokens=line.split()
        try:
            nums=[float(t) for t in tokens]
        except ValueError:
            if tokens[:2]==['<','0.1']:
                nums=[float(t) for t in tokens[2:]]
            else:
                continue
        if len(nums) in (13,14):
            rows.append(nums[-12:])
    assert len(rows)==24,(page,len(rows))
    tables[str(page)]=rows
    si=page in (385,387)
    family='mea_dea' if page<386 else 'mdea'
    for r,row in enumerate(rows):
        for col,native in enumerate(row):
            t=(88,93,104,116,127,132)[col//2]+273.15 if si else ((190,200,220,240,260,270)[col//2]-32)*5/9+273.15
            cells.append(dict(source_page=page,table_family=family,loading_mol_mol=.05 if r//3==0 else (.15,.25,.35,.45,.55,.65,.7)[r//3-1],
                contaminant_row=('low','middle','high')[r%3],maximum_temperature_k=t,velocity_m_s=0. if col%2==0 else 10.,
                unit_basis='printed_si' if si else 'printed_us_converted',native_rate=native,expected_rate_m_year=native*(.001 if si else .0000254)))
assert tables['384']==tables['386'] and tables['385']==tables['387']
assert len(cells)==1152
body=text.split('=== PDF PAGE 388 ===')[1].split('=== PDF PAGE')[0].split('Table 2.B.8.5')[1]
ss=[]
for line in body.splitlines():
    try:
        row=[float(v) for v in line.split()]
    except ValueError:
        continue
    if len(row)==3:
        ss.append(row)
assert len(ss)==8
Path('tests/fixtures/amine_source_tables.json').write_text(json.dumps(dict(source_pdf_sha256=hashlib.sha256(Path('API-581-2016.pdf').read_bytes()).hexdigest(),
    note='Independent text extraction visually checked against PDF384-388; spaced decimals normalized.',carbon_cells=cells,stainless_rows=ss),indent=2)+'\n',encoding='utf-8')
# Runtime tables are explicit checked-in data, with separate source table identities.
data=dict(mea_dea_us=tables['384'],mea_dea_si=tables['385'],mdea_us=tables['386'],mdea_si=tables['387'],stainless=ss)
Path('src/api581/_amine_tables.py').write_text('"""Checked 2016 amine source rows; generated by scripts/extract_amine_source_fixture.py."""\nTABLES = '+pformat(data,width=120,sort_dicts=False)+'\n',encoding='utf-8')
print('Amine source:',len(cells),'carbon cells and',len(ss)*2,'stainless cells')
