"""Visually checked 2016 sulfidic/naphthenic source rows and regression fixture."""
import hashlib
import json
import re
from pathlib import Path
from pprint import pformat

text=Path('tmp/pdfs/API-581-2016.txt').read_text(encoding='utf-8')
groups=['carbon_steel','low_alloy','cr5','cr7','cr9','cr12','stainless_no_mo','stainless_low_mo','stainless_high_mo']
tables={};cells=[]
for group_index,group in enumerate(groups):
    tans=(.3,.65,1.5,3.,4.) if group_index<2 else (.7,1.1,1.75,3.,4.) if group_index<6 else (1.,1.5,3.,4.) if group_index==6 else (.2,3.,4.) if group_index==7 else (4.,5.,6.)
    sulfurs=(.2,.4,.6,1.5,2.5,3.) if group_index==0 else (.2,.4,.75,1.5,2.5,3.) if group_index==2 else (.2,.4,.8,1.5,2.5,3.)
    for si in (False,True):
        page=334+2*group_index+int(si)
        body=text.split(f'=== PDF PAGE {page} ===')[1].split('=== PDF PAGE')[0]
        rows=[]
        for line in body.splitlines():
            line=line.replace('\ufffd','').replace('\u00b7','') # nonnumeric OCR artifact between checked cells
            line=re.sub(r'(\d)\s+\.(\d)',r'\1.\2',line)
            line=line.replace('0.1 0','0.10') # checked rendered0.10, e.g.pages341/343
            if page==343: line=line.replace('4.0 0.1 3 ','4.0 0.13 ')
            try: values=[float(v) for v in line.split()]
            except ValueError: continue
            if len(values) not in (9,10): continue
            expected_tan=tans[len(rows)%len(tans)]
            expected_sulfur=sulfurs[len(rows)//len(tans)]
            if len(values)==10:
                candidates=[values[:k]+values[k+1:] for k,v in enumerate(values) if v==expected_sulfur]
                values=next((v for v in candidates if v[0]==expected_tan),None)
                assert values is not None,(page,line,expected_sulfur,expected_tan)
            assert values[0]==expected_tan,(page,line,expected_tan)
            rows.append(values[1:])
        assert len(rows)==6*len(tans),(page,len(rows))
        unit='printed_si' if si else 'printed_us_converted'
        data=dict(sulfur_mass_fractions=[s/100 for s in sulfurs],tan_mg_koh_g=list(tans),rates=rows)
        tables[group+'_'+unit]=data
        for r,values in enumerate(rows):
            for t,rate in enumerate(values):
                # Edge-bin representative samples for contract tests, not invented table nodes.
                temperature=(232,260,288,315,343,371,399,400)[t]+273.15 if si else ((450,500,550,600,650,700,750,751)[t]-32)*5/9+273.15
                cells.append(dict(table_group=group,unit_basis=unit,sulfur_mass_fraction=sulfurs[r//len(tans)]/100,tan_mg_koh_g=tans[r%len(tans)],
                    maximum_temperature_k=temperature,source_page=page,temperature_column_index=t,native_rate=rate,expected_rate_m_year=rate*(.001 if si else .0000254)))
assert len(cells)==3840
Path('src/api581/_sulfidic_tables.py').write_text('"""2016 sulfidic/naphthenic tables; generated by scripts/extract_sulfidic_source_fixture.py."""\nTABLES = '+pformat(tables,width=120,sort_dicts=False)+'\n',encoding='utf-8')
Path('tests/fixtures/sulfidic_source_tables.json').write_text(json.dumps(dict(source_pdf_sha256=hashlib.sha256(Path('API-581-2016.pdf').read_bytes()).hexdigest(),
    note='Runtime and fixture share extraction. Rendered first temperature header is<=; edge sample temperatures are test representatives. OCR embedded sulfur column/spaced decimals normalized after rendering review.',cells=cells),indent=2)+'\n',encoding='utf-8')
print('Sulfidic/naphthenic physical cells:',len(cells))
