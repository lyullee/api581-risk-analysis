"""Visually checked 2016 high-temperature H2S/H2 table extraction."""
import hashlib
import json
import re
from pathlib import Path
from pprint import pformat

text=Path('tmp/pdfs/API-581-2016.txt').read_text(encoding='utf-8')
pages={n:text.split(f'=== PDF PAGE {n} ===')[1].split('=== PDF PAGE')[0] for n in range(354,363)}
tables={};cells=[]
concentrations=[.002,.0035,.008,.035,.08,.30,.75,1.0]
for group,us_page,si_page in [('carbon_low_alloy',354,355),('cr5',356,357),('cr7',358,359),('cr9',360,361),('cr12',361,362),('stainless',362,362)]:
    branch=group not in ('cr12','stainless')
    for si,page in ((False,us_page),(True,si_page)):
        body=pages[page]
        if group=='cr9' and si:
            body=body.split('Table 2.8.4.6')[0]
        elif group=='cr12':
            body=body.split('Table 2.8.4.6' if not si else 'Table 2.B.4.6M',1)[1]
            if si: body=body.split('Table 2.B.4.7')[0]
        elif group=='stainless':
            body=body.split('Table 2.B.4.7M' if si else 'Table 2.B.4.7 -',1)[1]
            if not si: body=body.split('Table 2.B.4.7M')[0]
        data=[]
        for line in body.splitlines():
            line=re.sub(r'(\d)\s+\.(\d)',r'\1.\2',line)
            if branch:
                match=re.search(r'(?:Naphtha|Gas Oil)\s+',line)
                if not match: continue
                # Some9Cr rows print merged H2S value after12rates.
                try: values=[float(v) for v in line[match.end():].split()]
                except ValueError: continue
                assert len(values) in (12,13),(page,line)
                values=values[:12]
            else:
                try: values=[float(v) for v in line.split()]
                except ValueError: continue
                if len(values)!=13: continue
                values=values[1:]
            data.append(values)
        assert len(data)==(16 if branch else 8),(group,page,len(data))
        unit='printed_si' if si else 'printed_us_converted'
        tables[group+'_'+unit]=data
        for row,values in enumerate(data):
            c=concentrations[row//2 if branch else row]/100
            curve=('naphtha','gas_oil')[row%2] if branch else None
            for t,native in enumerate(values):
                temp=(218,246,274,302,329,357,385,413,441,468,496,524)[t]+273.15 if si else ((425,475,525,575,625,675,725,775,825,875,925,975)[t]-32)*5/9+273.15
                cells.append(dict(table_group=group,unit_basis=unit,h2s_mole_fraction=c,curve=curve,maximum_temperature_k=temp,
                    source_page=page,native_rate=native,expected_rate_m_year=native*(.001 if si else .0000254)))
assert len(cells)==1920
Path('src/api581/_h2sh2_tables.py').write_text('"""2016 H2S/H2 source rates; generated by scripts/extract_h2sh2_source_fixture.py."""\nTABLES = '+pformat(tables,width=120,sort_dicts=False)+'\n',encoding='utf-8')
Path('tests/fixtures/h2sh2_source_tables.json').write_text(json.dumps(dict(source_pdf_sha256=hashlib.sha256(Path('API-581-2016.pdf').read_bytes()).hexdigest(),
    note='Runtime data and fixture share source extraction. Spaced OCR decimals normalized after PDF354-362 rendering review.',cells=cells),indent=2)+'\n',encoding='utf-8')
print('H2S/H2 source physical cells:',len(cells))
